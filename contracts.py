"""
contracts.py - Data Contracts and Pydantic Schemas
Defines core schema definitions for the AI IT Incident Response Agent system.
Strict validation ensures that data flowing through prompt chaining, worker execution,
and evaluator-optimizer loops conforms to strict structural invariants.
"""

from datetime import datetime, timezone
from typing import Any, Dict, List, Optional
import uuid
from pydantic import BaseModel, Field


def generate_incident_id() -> str:
    """Generate a unique human-readable Incident ID."""
    return f"INC-{uuid.uuid4().hex[:6].upper()}"


class TriageResult(BaseModel):
    """
    Structured output produced by the Incident Triage Agent.
    Contains classification, severity, scope, and initial investigation plan.
    """
    incident_id: str = Field(
        default_factory=generate_incident_id,
        description="Unique identifier for the reported incident (e.g. INC-A1B2C3)."
    )
    category: str = Field(
        ...,
        description="Primary domain of the incident: 'Account', 'Device', 'Network', 'Security', or 'General IT'."
    )
    severity: str = Field(
        ...,
        description="Severity level: 'Low', 'Medium', 'High', or 'Critical'."
    )
    is_security_incident: bool = Field(
        ...,
        description="Deterministic flag: True if unauthorized access, malware, breach, phishing, or policy violation."
    )
    affected_user: Optional[str] = Field(
        default=None,
        description="Identifier of the affected employee/user (e.g. 'usr_alice')."
    )
    affected_device: Optional[str] = Field(
        default=None,
        description="Identifier of the affected machine/endpoint (e.g. 'dev_mac_101')."
    )
    affected_location_or_ip: Optional[str] = Field(
        default=None,
        description="IP address, subnet, or branch office location (e.g. '10.0.4.1', 'HQ-Floor2')."
    )
    summary: str = Field(
        ...,
        description="Concise description of the problem reported by the user."
    )
    investigation_plan: List[str] = Field(
        default_factory=list,
        description="Sequential list of investigative steps to execute."
    )
    recommended_workers: List[str] = Field(
        default_factory=list,
        description="List of specialized sub-agents needed: ['Account Worker', 'Device Worker', 'Network Worker']."
    )


class DiagnosticReport(BaseModel):
    """
    Diagnostic telemetry produced by a specialized worker or tool call.
    Represents concrete, grounded evidence gathered from infrastructure.
    """
    worker_name: str = Field(
        ...,
        description="Name of the worker that executed the diagnostic."
    )
    target_id: str = Field(
        ...,
        description="Target entity examined (user_id, device_id, location, or query)."
    )
    status: str = Field(
        ...,
        description="Health / operational status: 'Healthy', 'Warning', 'Error', 'Compromised', or 'Offline'."
    )
    details: Dict[str, Any] = Field(
        default_factory=dict,
        description="Structured key-value metrics and diagnostic properties."
    )
    raw_evidence: str = Field(
        ...,
        description="Verbatim diagnostic logs, configuration flags, or runbook snippets."
    )
    timestamp: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="ISO 8601 timestamp of diagnostic execution."
    )


class ResolutionDraft(BaseModel):
    """
    Candidate remediation plan generated by the Troubleshooting Agent.
    Must be reviewed and grounded by the Evaluator Agent before approval.
    """
    incident_id: str = Field(
        ...,
        description="ID of the incident being resolved."
    )
    root_cause: str = Field(
        ...,
        description="Root cause hypothesis derived directly from gathered diagnostic evidence."
    )
    proposed_actions: List[str] = Field(
        default_factory=list,
        description="List of immediate corrective actions required."
    )
    resolution_steps: List[str] = Field(
        default_factory=list,
        description="End-user actionable guidance or technician runbook steps."
    )
    requires_escalation: bool = Field(
        default=False,
        description="True if the issue requires senior IT technician or Human-in-the-Loop review."
    )
    escalation_reason: Optional[str] = Field(
        default=None,
        description="Justification for human escalation if required."
    )
    confidence_score: float = Field(
        ge=0.0,
        le=1.0,
        description="Confidence level in the validity of the proposed resolution (0.0 to 1.0)."
    )
    is_autonomous_closure_allowed: bool = Field(
        default=True,
        description="Deterministic flag: True if the agent may close the ticket autonomously."
    )


class EvaluationVerdict(BaseModel):
    """
    Verification critique issued by the Evaluator Agent during the Evaluator-Optimizer loop.
    Audits the ResolutionDraft for groundedness, safety, and completeness.
    """
    is_grounded: bool = Field(
        ...,
        description="True if all claims and steps are strictly supported by DiagnosticReport evidence."
    )
    is_safe: bool = Field(
        ...,
        description="True if proposed remediation complies with IT security policies and administrative guardrails."
    )
    is_complete: bool = Field(
        ...,
        description="True if all user symptoms and affected components are addressed."
    )
    approved: bool = Field(
        ...,
        description="True if the draft is approved for final delivery to the user."
    )
    critique: str = Field(
        ...,
        description="Constructive critique detailing groundedness gaps or safety concerns."
    )
    missing_evidence: List[str] = Field(
        default_factory=list,
        description="Specific claims in the draft lacking diagnostic proof."
    )
    revision_suggestions: List[str] = Field(
        default_factory=list,
        description="Clear, directive instructions for the Troubleshooting Agent to correct the draft."
    )
    iteration: int = Field(
        default=1,
        description="Current iteration in the Evaluator-Optimizer loop (max 3)."
    )


class IncidentAuditRecord(BaseModel):
    """
    Comprehensive record of the end-to-end incident lifecycle for traceability and compliance.
    """
    incident_id: str
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    user_report: str
    triage: TriageResult
    diagnostics: List[DiagnosticReport] = Field(default_factory=list)
    evaluation_history: List[EvaluationVerdict] = Field(default_factory=list)
    final_resolution: Optional[ResolutionDraft] = None
    ticket_id: Optional[str] = None
    status: str = "In Progress"
    execution_notes: List[str] = Field(default_factory=list)

